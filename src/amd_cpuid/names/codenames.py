def lookup_codename(family: int, model: int) -> str:
    """Return the marketing codename for a ``(family, model)`` pair.

    For example ``"Matisse"``. Returns ``"Unknown"`` when the model is not in
    the table.
    """
    return _CODENAMES.get((family, model), UNKNOWN)
